/* ── Terminal line ── */
function TermLine({ prompt = '$', cmd, out, delay = 0 }) {
  const ref = useRef(null)
  const inView = useInView(ref, { once: true })
  return (
    <motion.div ref={ref} initial={{ opacity: 0 }} animate={inView ? { opacity: 1 } : {}} transition={{ delay }}
      className="font-mono text-xs leading-relaxed">
      <div><span className="text-cyan-400">{prompt}</span> <span className="text-white/80">{cmd}</span></div>
      {out && <div className="text-white/35 ml-4">{out}</div>}
    </motion.div>
  )
}

