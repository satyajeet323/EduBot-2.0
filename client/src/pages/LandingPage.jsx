/* ── Typewriter hook ── */
function useTypewriter(words, speed = 80, pause = 1800) {
  const [display, setDisplay] = useState('')
  const [wIdx, setWIdx] = useState(0)
  const [typing, setTyping] = useState(true)
  useEffect(() => {
    const word = words[wIdx]
    if (typing) {
      if (display.length < word.length) {
        const t = setTimeout(() => setDisplay(word.slice(0, display.length + 1)), speed)
        return () => clearTimeout(t)
      } else {
        const t = setTimeout(() => setTyping(false), pause)
        return () => clearTimeout(t)
      }
    } else {
      if (display.length > 0) {
        const t = setTimeout(() => setDisplay(display.slice(0, -1)), speed / 2)
        return () => clearTimeout(t)
      } else {
        setWIdx((wIdx + 1) % words.length)
        setTyping(true)
      }
    }
  }, [display, typing, wIdx])
  return display
}

/* ── Scroll reveal ── */
function Reveal({ children, delay = 0, x = 0, y = 40 }) {
  const ref = useRef(null)
  const inView = useInView(ref, { once: true, margin: '-60px' })
  return (
    <motion.div ref={ref}
      initial={{ opacity: 0, x, y }}
      animate={inView ? { opacity: 1, x: 0, y: 0 } : {}}
      transition={{ duration: 0.7, delay, ease: [0.22, 1, 0.36, 1] }}>
      {children}
    </motion.div>
  )
}

